/** How long to wait for `method`'s answer; null to wait as long as it takes. */
export function hostRequestLimit(method: string): number | null {
  return Object.hasOwn(HOST_REQUEST_LIMITS, method)
    ? HOST_REQUEST_LIMITS[method as HostMethod]
    : null
}
